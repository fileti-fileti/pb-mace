#!/usr/bin/env python3
"""Prepare the q1 check of the Na relabelling protocol (docs/na-relabel.md, ADR-0016).

Usage (headnode, clean work tree; nothing is submitted, the sbatch commands are printed):
  prep_na_q1_check.py CONFIG --name RUN

CONFIG: configs/na_relabel/*.json. The script
- draws the frames from consolidado/frames.tsv (checked against its sha256 list): per
  stratum, in the config's order, random.Random(seed).sample(rows, n_per_stratum) over the
  rows of the draw's split (train or valid only) whose config_type is in the stratum and
  whose origem is eligible, sorted by i. Eligible: no parcial_* path part, no parcial_*
  subdir, and its relabel.inp uses the seeded protocol (SCF_GUESS RESTART from
  WFN_RESTART_FILE_NAME = q9_seed, EXTRAPOLATION USE_GUESS, U_RAMPING 0, no ramp each SCF);
- takes the base input: relabel.inp of the first drawn frame's origem (the seeded label
  protocol: SCF_GUESS RESTART from WFN_RESTART_FILE_NAME = q9_seed, full U from the first
  SCF step, EXTRAPOLATION USE_GUESS, 700/70). Every drawn origem must have the same input
  apart from SEED, STEPS, LAST_SNAPSHOT and blank lines, and an include with the same kind
  column. The seed-generation input is seed_protocol_dir's relabel.inp (the atomic-guess
  label protocol), which must differ from the base only in the state lines (SEED,
  WFN_RESTART_FILE_NAME, SCF_GUESS, INIT_U_RAMPING_EACH_SCF, U_RAMPING, STEPS, LAST_SNAPSHOT);
- writes runs/RUN/:
  seed_q9.wfn     a copy of q9_seed (the seed of the legacy labels);
  q1-seed/        job.sh, shared files and seed_gen/: one single point of the first drawn
                  frame with the seed-generation input and Na q1 at 700/70; the job copies
                  seed_gen/<project>-RESTART.wfn to q1-seed/seed.wfn;
  <setting>/      relabel.inp (the base input with only: CUTOFF, REL_CUTOFF, the Na KIND for
                  q1, WFN_RESTART_FILE_NAME seed.wfn, REFTRAJ on one snapshot of pool.xyz),
                  seed.wfn (symlink to ../seed_q9.wfn or ../q1-seed/seed.wfn), the include,
                  basis/potential/D3 files, job.sh (runs the frames in turn; a frame whose
                  relabel.out ended is skipped, so a resubmission resumes), and one dir per
                  frame of the setting (fNN: pool.xyz with its snapshot, a copy of
                  relabel.inp, ref_frc.xyz = the legacy label forces in Ha/bohr, symlinks to
                  the shared files);
  run_info.json   commit, config sha256, the draw, per frame its frames.tsv row, legacy Fe
                  spins and energy, per setting its frames and copied files (sha256).
A setting's frames are "all" or "repro" (the first drawn frame of each repro stratum).
Checks here: machine, CP2K module and partition in its YAML; clean tree; frames.tsv sha256;
atom count and element order (pool, legacy forces, include); every edit hits one line with
the expected old value; every KIND's basis set and potential exist; legacy Fe spins for
every frame; enough eligible rows per stratum; the run dir is new.
Standard library only; runs on Python >= 3.6.
"""
import argparse
import datetime
import json
import random
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
import machine_config as mc  # noqa: E402
import prep_mace_train as pm  # noqa: E402  (git, sha256, parse_time)
import prep_na_translation as pt  # noqa: E402  (xyz, forces, input edits, kinds)
import prep_na_translation_v2 as p2  # noqa: E402  (legacy Fe spins)
from prep_na_translation import PrepError  # noqa: E402

TOP_KEYS = {"description", "legacy_root", "frames_tsv", "frames_tsv_sums", "cp2k_data_dir",
            "draw", "seed_protocol_dir", "q9_seed", "na_q1", "forces_file", "seed_job_time",
            "settings", "slurm"}
DRAW_KEYS = {"seed", "split", "n_per_stratum", "strata", "repro_strata"}
SETTING_KEYS = {"cutoff", "rel_cutoff", "na", "frames", "time"}
STATE_KEYS = {"SEED", "WFN_RESTART_FILE_NAME", "SCF_GUESS", "INIT_U_RAMPING_EACH_SCF",
              "U_RAMPING", "STEPS", "LAST_SNAPSHOT"}
BATCH_KEYS = {"SEED", "STEPS", "LAST_SNAPSHOT"}
SEEDED = (("CUTOFF", "700"), ("REL_CUTOFF", "70"), ("EXTRAPOLATION", "USE_GUESS"),
          ("SCF_GUESS", "RESTART"), ("INIT_U_RAMPING_EACH_SCF", "F"), ("U_RAMPING", "[eV] 0.0"))
ATOMIC = (("CUTOFF", "700"), ("REL_CUTOFF", "70"), ("EXTRAPOLATION", "USE_GUESS"),
          ("SCF_GUESS", "ATOMIC"), ("INIT_U_RAMPING_EACH_SCF", "T"), ("U_RAMPING", "[eV] 0.5"))

JOB = """#!/bin/bash
# Generated by scripts/prep_na_q1_check.py at commit {commit}; re-run it instead of editing.
# Layout: {ntasks} MPI x {cpt} OpenMP; source: {layout_source}
#SBATCH --job-name={jobname}
#SBATCH -N 1
#SBATCH -n {ntasks}
#SBATCH --cpus-per-task={cpt}
#SBATCH -p {partition}
#SBATCH -w {nodelist}
#SBATCH --output=slurm-%j.out
#SBATCH --error=slurm-%j.err
#SBATCH --time={time}
#SBATCH --mem=0
set -euo pipefail
module purge
module load {module}
export OMP_NUM_THREADS=$SLURM_CPUS_PER_TASK
export MKL_NUM_THREADS=$SLURM_CPUS_PER_TASK
export STACKSIZE=1G
export LIBXSMM_DEFAULT_QUANTIZATION=1
RUNDIR=$PWD
cp2k_in() {{  # run CP2K in dir $1 unless its relabel.out already ended
  cd "$RUNDIR/$1"
  if grep -q "PROGRAM ENDED" relabel.out 2>/dev/null; then echo "$1: done, skipped"; return; fi
  [ -e relabel.out ] && mv relabel.out "relabel.out.partial.$SLURM_JOB_ID"
  echo "$1: start $(date '+%F %T')"
  mpirun --mca opal_set_max_sys_limits 1 --mca btl ^openib \\
         cp2k.psmp -i relabel.inp -o relabel.out
  echo "$1: end $(date '+%F %T')"
}}
echo "start $(date '+%F %T') on $(hostname)"
{body}
echo "end $(date '+%F %T')"
"""
BODY_SETTING = """[ -s "$RUNDIR/seed.wfn" ] || {{ echo "no seed.wfn: stop" >&2; exit 1; }}
for d in {dirs}; do cp2k_in $d; done"""
BODY_SEED = """cp2k_in seed_gen
cd "$RUNDIR"
[ -s seed.wfn ] || cp seed_gen/{project}-RESTART.wfn seed.wfn"""


# ----------------------------------------------------------------------------- config
def load_config(path):
    cfg = json.loads(Path(path).read_text())
    errs = ["config: {} key {!r}".format("unknown" if k in cfg else "missing", k)
            for k in sorted(set(cfg) ^ TOP_KEYS)]
    if errs:
        raise PrepError("; ".join(errs))
    d = cfg["draw"]
    errs += ["draw: {} key {!r}".format("unknown" if k in d else "missing", k)
             for k in sorted(set(d) ^ DRAW_KEYS)]
    if not errs:
        if d["split"] not in ("train", "valid"):
            errs.append("draw.split must be train or valid (training side)")
        if not isinstance(d["n_per_stratum"], int) or d["n_per_stratum"] < 1:
            errs.append("draw.n_per_stratum must be an integer >= 1")
        names = [s[0] for s in d["strata"]]
        if len(set(names)) != len(names) or any(len(s) != 2 or not s[1] for s in d["strata"]):
            errs.append("draw.strata: [[name, [config_type, ...]], ...] with unique names")
        if not set(d["repro_strata"]) <= set(names):
            errs.append("draw.repro_strata: unknown stratum")
    for n, s in cfg["settings"].items():
        errs += ["settings.{}: {} key {!r}".format(n, "unknown" if k in s else "missing", k)
                 for k in sorted(set(s) ^ SETTING_KEYS)]
        if set(s) == SETTING_KEYS:
            if s["na"] not in ("q9", "q1"):
                errs.append("settings.{}: na must be q9 or q1".format(n))
            if s["frames"] not in ("all", "repro"):
                errs.append("settings.{}: frames must be all or repro".format(n))
            try:
                pm.parse_time(s["time"])
            except pm.PrepError as e:
                errs.append("settings.{}: {}".format(n, e))
    try:
        pm.parse_time(cfg["seed_job_time"])
    except pm.PrepError as e:
        errs.append("seed_job_time: {}".format(e))
    if errs:
        raise PrepError("; ".join(errs))
    return cfg


# ----------------------------------------------------------------------------- draw
def read_tsv(text):
    rows = [l.split("\t") for l in text.splitlines() if l.strip()]
    return [dict(zip(rows[0], r)) for r in rows[1:]]


def seeded(text, q9_seed):
    """True if a legacy relabel.inp uses the seeded label protocol (state held by q9_seed)."""
    return (all(pt.kw_values(text, k) == [v] for k, v in SEEDED[2:])
            and pt.kw_values(text, "WFN_RESTART_FILE_NAME") == [str(q9_seed)])


def eligible(origem, legacy, q9_seed, cache):
    d = (legacy / origem).parent
    if d not in cache:
        cache[d] = (not any(p.startswith("parcial_") for p in Path(origem).parts)
                    and (d / "relabel.inp").is_file()
                    and not any(c.is_dir() and c.name.startswith("parcial_")
                                for c in d.iterdir())
                    and seeded((d / "relabel.inp").read_text(), q9_seed))
    return cache[d]


def draw(rows, d, legacy, q9_seed):
    """-> [(stratum, row)] in draw order."""
    rng, cache, out = random.Random(d["seed"]), {}, []
    for name, types in d["strata"]:
        pool = sorted((r for r in rows if r["destino"] == d["split"]
                       and r["config_type"] in types
                       and eligible(r["origem"], legacy, q9_seed, cache)),
                      key=lambda r: int(r["i"]))
        if len(pool) < d["n_per_stratum"]:
            raise PrepError("stratum {}: {} eligible rows, need {}".format(
                name, len(pool), d["n_per_stratum"]))
        out += [(name, r) for r in rng.sample(pool, d["n_per_stratum"])]
    return out


# ----------------------------------------------------------------------------- inputs
def core_lines(text, drop):
    return [l.rstrip() for l in text.splitlines()
            if l.split() and l.split()[0].upper() not in drop]


def same_protocol(a, b, drop, where):
    la, lb = core_lines(a, drop), core_lines(b, drop)
    if la != lb:
        diff = [(x, y) for x, y in zip(la, lb) if x != y][:2] or "line count {} vs {}".format(
            len(la), len(lb))
        raise PrepError("{}: input differs beyond {}: {}".format(where, sorted(drop), diff))


def expect(text, pairs, where):
    for key, val in pairs:
        if pt.kw_values(text, key) != [val]:
            raise PrepError("{}: {} expected [{!r}], found {}".format(
                where, key, val, pt.kw_values(text, key)))


def one_snapshot(text):
    text = pt.set_kw(text, "TRAJ_FILE_NAME", "pool.xyz", old="pool_lote.xyz")
    text = pt.set_kw(text, "FIRST_SNAPSHOT", 1)
    text = pt.set_kw(text, "LAST_SNAPSHOT", 1)
    return pt.set_kw(text, "STEPS", 1)


def setting_input(base, st, na_q1, q9_seed):
    expect(base, SEEDED, "base input")
    if pt.kw_values(base, "WFN_RESTART_FILE_NAME") != [str(q9_seed)]:
        raise PrepError("base input: WFN_RESTART_FILE_NAME is not {}".format(q9_seed))
    text = pt.set_kw(base, "CUTOFF", st["cutoff"], old="700")
    text = pt.set_kw(text, "REL_CUTOFF", st["rel_cutoff"], old="70")
    text = pt.set_kw(text, "WFN_RESTART_FILE_NAME", "seed.wfn")
    if st["na"] == "q1":
        text = pt.swap_na(text, na_q1)
    return one_snapshot(text)


def seed_input(gen_base, na_q1):
    expect(gen_base, ATOMIC, "seed-generation input")
    if pt.kw_values(gen_base, "WFN_RESTART_FILE_NAME"):
        raise PrepError("seed-generation input: has WFN_RESTART_FILE_NAME")
    return one_snapshot(pt.swap_na(gen_base, na_q1))


def kind_column(text):
    return [l.split()[0] for l in text.splitlines()
            if len(l.split()) >= 4 and not l.split()[0].startswith(("#", "&", "@", "!"))]


def gather_files(text, src, data_dir, n_atoms_els, where):
    """-> {name: source path} for the include and the basis/potential/D3 files."""
    inc = re.findall(r"^[ \t]*@INCLUDE[ \t]+(\S+)", text, re.M)
    if len(inc) != 1:
        raise PrepError("{}: expected one @INCLUDE, found {}".format(where, inc))
    files = {inc[0]: pt.find_file(inc[0], [src])}
    if pt.include_elements(files[inc[0]].read_text(), pt.kinds(text)) != n_atoms_els:
        raise PrepError("{}: {} element order differs from the pool".format(where, inc[0]))
    libs = pt.kw_values(text, "BASIS_SET_FILE_NAME") + pt.kw_values(text, "POTENTIAL_FILE_NAME") \
        + pt.kw_values(text, "PARAMETER_FILE_NAME")
    for lib in libs:
        files[lib] = pt.find_file(lib, [src, data_dir])
    pt.check_kinds(text, {k: v.read_text() for k, v in files.items() if k in libs})
    return files


# ----------------------------------------------------------------------------- prepare
def prepare(repo, cfg_path, name, machine=None, mcfg=None, now=None):
    repo = Path(repo).resolve()
    cfg_path = Path(cfg_path)
    cfg_path = (cfg_path if cfg_path.is_absolute() else repo / cfg_path).resolve()
    if not cfg_path.is_file():
        raise PrepError("{}: no such config".format(cfg_path))
    if machine is None:
        machine = mc.detect(repo)
        mcfg = mc.load(machine, repo)
    if pm.git(repo, "status", "--porcelain").strip():
        raise PrepError("work tree not clean: commit first (runs record their commit)")
    commit = pm.git(repo, "rev-parse", "HEAD").strip()
    cfg = load_config(cfg_path)
    sl = cfg["slurm"]
    module = mcfg.get("modules", {}).get("cp2k", mc.UNKNOWN)
    if module == mc.UNKNOWN:
        raise PrepError("modules.cp2k unknown in the {} YAML".format(machine))
    if sl["partition"] not in mcfg["partitions"]:
        raise PrepError("partition {!r} not in the {} YAML".format(sl["partition"], machine))
    legacy, data_dir = Path(cfg["legacy_root"]), Path(cfg["cp2k_data_dir"])
    tsv, sums = legacy / cfg["frames_tsv"], repo / cfg["frames_tsv_sums"]
    if not sums.is_file() or pm.sha256(tsv) != pt.sum_for(sums.read_text(), tsv.name):
        raise PrepError("{}: missing checksum list or sha256 differs".format(tsv))
    out = repo / "runs" / name
    if out.exists():
        raise PrepError("{}: exists (runs are never overwritten)".format(out))
    q9_seed = legacy / cfg["q9_seed"]
    if not q9_seed.is_file() or q9_seed.stat().st_size == 0:
        raise PrepError("q9 seed {}: missing or empty".format(q9_seed))
    ff = cfg["forces_file"]

    drawn = draw(read_tsv(tsv.read_text()), cfg["draw"], legacy, q9_seed)
    frames, base, base_src, kinds0 = [], None, None, None
    for k, (stratum, row) in enumerate(drawn, 1):
        src = (legacy / row["origem"]).parent
        snap = int(row["frame"])
        inp = (src / "relabel.inp").read_text()
        where = "{} snapshot {}".format(row["origem"], snap)
        n, comment, atoms = pt.read_xyz_frame((src / "pool_lote.xyz").read_text(), snap,
                                              str(src / "pool_lote.xyz"))
        forces = pt.read_forces((src / ff).read_text(), snap, str(src / ff))
        if [a[0] for a in forces] != [a[0] for a in atoms]:
            raise PrepError("{}: force file and pool disagree on elements".format(where))
        inc = re.findall(r"^[ \t]*@INCLUDE[ \t]+(\S+)", inp, re.M)
        kc = kind_column(pt.find_file(inc[0], [src]).read_text()) if len(inc) == 1 else None
        if base is None:
            base, base_src, kinds0 = inp, src, kc
        else:
            same_protocol(base, inp, BATCH_KEYS, where)
            if kc != kinds0:
                raise PrepError("{}: include kind column differs from {}".format(where, base_src))
        frames.append({"id": "f{:02d}".format(k), "stratum": stratum, "row": row, "src": src,
                       "snapshot": snap, "atoms": atoms, "forces": forces, "comment": comment,
                       "spins": p2.legacy_fe_spins((src / "relabel.out").read_text(), snap),
                       "inp_sha256": pm.sha256(src / "relabel.inp")})
    els = [a[0] for a in frames[0]["atoms"]]
    for f in frames:
        if [a[0] for a in f["atoms"]] != els:
            raise PrepError("{}: element order differs from f01".format(f["row"]["origem"]))
    repro = [next(f["id"] for f in frames if f["stratum"] == s)
             for s in cfg["draw"]["repro_strata"]]
    project = pt.kw_values(base, "PROJECT")[0]

    gsrc = legacy / cfg["seed_protocol_dir"]
    gen_base = (gsrc / "relabel.inp").read_text()
    same_protocol(base, gen_base, STATE_KEYS, str(gsrc))
    ginc = re.findall(r"^[ \t]*@INCLUDE[ \t]+(\S+)", gen_base, re.M)
    if len(ginc) != 1 or kind_column(pt.find_file(ginc[0], [gsrc]).read_text()) != kinds0:
        raise PrepError("{}: include kind column differs from {}".format(gsrc, base_src))
    gen = seed_input(gen_base, cfg["na_q1"])
    gen_files = gather_files(gen, gsrc, data_dir, els, str(gsrc))

    plan = {}
    for sname, st in cfg["settings"].items():
        text = setting_input(base, st, cfg["na_q1"], q9_seed)
        plan[sname] = {"text": text, "files": gather_files(text, base_src, data_dir, els, sname),
                       "frames": [f for f in frames
                                  if st["frames"] == "all" or f["id"] in repro]}

    out.mkdir(parents=True)
    shutil.copyfile(str(q9_seed), str(out / "seed_q9.wfn"))
    info = {"created": (now or datetime.datetime.now()).isoformat(timespec="seconds"),
            "machine": machine, "commit": commit, "config": str(cfg_path.relative_to(repo)),
            "config_sha256": pm.sha256(cfg_path), "frames_tsv_sha256": pm.sha256(tsv),
            "draw": cfg["draw"], "forces_file": ff, "project": project,
            "base_input": {"dir": str(base_src), "sha256": pm.sha256(base_src / "relabel.inp")},
            "q9_seed": {"source": str(q9_seed), "sha256": pm.sha256(out / "seed_q9.wfn")},
            "seed_frame": frames[0]["id"], "repro_frames": repro,
            "frames": [{"id": f["id"], "stratum": f["stratum"], "i": int(f["row"]["i"]),
                        "config_type": f["row"]["config_type"], "grupo": f["row"]["grupo"],
                        "destino": f["row"]["destino"], "origem": f["row"]["origem"],
                        "snapshot": f["snapshot"], "legacy_E_eV": float(f["row"]["E_eV"]),
                        "legacy_inp_sha256": f["inp_sha256"], "legacy_fe_spins": f["spins"]}
                       for f in frames],
            "settings": {}}

    def write_dir(rd, text, files, dirs, shared_extra):
        rd.mkdir()
        (rd / "relabel.inp").write_text(text)
        sha = {}
        for fn, srcp in sorted(files.items()):
            shutil.copyfile(str(srcp), str(rd / fn))
            sha[fn] = {"source": str(srcp), "sha256": pm.sha256(rd / fn)}
        for dname, f in dirs:
            d = rd / dname
            d.mkdir()
            (d / "relabel.inp").write_text(text)
            (d / "pool.xyz").write_text(pt.write_xyz([(
                "{} | legacy {} snapshot {} | {}".format(
                    f["id"], f["row"]["origem"], f["snapshot"], f["comment"].strip()),
                f["atoms"])]))
            (d / "ref_frc.xyz").write_text(pt.write_xyz([(
                "legacy label forces [Ha/bohr] | {} snapshot {}".format(
                    str(f["src"] / ff), f["snapshot"]), f["forces"])]))
            for fn in sorted(files) + shared_extra:
                (d / fn).symlink_to(Path("..") / fn)
        return sha

    def job(rd, jobname, time, body):
        (rd / "job.sh").write_text(JOB.format(
            commit=commit, ntasks=sl["ntasks"], cpt=sl["cpus_per_task"],
            layout_source=sl["layout_source"], partition=sl["partition"],
            nodelist=sl["nodelist"], time=time, module=module, jobname=jobname, body=body))
        return "cd {} && sbatch job.sh".format(rd)

    rd = out / "q1-seed"
    sha = write_dir(rd, gen, gen_files, [("seed_gen", frames[0])], [])
    cmds = [job(rd, "naq1-seed", cfg["seed_job_time"], BODY_SEED.format(project=project))]
    info["seed_job"] = {"dir": str(gsrc), "input_sha256": pm.sha256(gsrc / "relabel.inp"),
                        "frame": frames[0]["id"], "time": cfg["seed_job_time"], "files": sha}
    for sname, st in cfg["settings"].items():
        p = plan[sname]
        rd = out / sname
        sha = write_dir(rd, p["text"], p["files"], [(f["id"], f) for f in p["frames"]],
                        ["seed.wfn"])
        (rd / "seed.wfn").symlink_to(Path("..") / ("seed_q9.wfn" if st["na"] == "q9"
                                                   else "q1-seed/seed.wfn"))
        cmds.append(job(rd, "naq1-" + sname, st["time"], BODY_SETTING.format(
            dirs=" ".join(f["id"] for f in p["frames"]))))
        info["settings"][sname] = dict(st, frames=[f["id"] for f in p["frames"]],
                                       frames_rule=st["frames"], files=sha,
                                       seed="seed_q9.wfn" if st["na"] == "q9"
                                       else "q1-seed/seed.wfn")
    (out / "run_info.json").write_text(json.dumps(info, indent=1, sort_keys=True) + "\n")
    return out, cmds


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("config")
    ap.add_argument("--name", required=True, help="run dir name under runs/")
    a = ap.parse_args(argv)
    repo = Path(__file__).resolve().parent.parent
    try:
        out, cmds = prepare(repo, a.config, a.name)
    except (PrepError, pm.PrepError, mc.ConfigError, OSError, ValueError) as e:
        print("prep_na_q1_check: " + str(e), file=sys.stderr)
        return 1
    print("prepared {} (nothing submitted). To submit (ask first; the q1 seed job first, its"
          " Fe spins checked, then the settings):".format(out))
    for c in cmds:
        print("  " + c)
    return 0


if __name__ == "__main__":
    sys.exit(main())

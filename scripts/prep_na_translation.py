#!/usr/bin/env python3
"""Prepare the rigid-translation test of the qz force labels (docs/na-label-grid-error.md).

Usage (headnode, clean work tree; nothing is submitted, the sbatch commands are printed):
  prep_na_translation.py CONFIG --name RUN

CONFIG: configs/na_translation/*.json. For every entry of "runs" ([frame, setting, wall
time]) this writes runs/RUN/<frame>-<setting>/ with
  relabel.inp  the frame's legacy qz input (copied from the legacy dir, ADR-0008) with only
               these edits: PRINT_LEVEL MEDIUM (prints the PW grids, to check N);
               EXTRAPOLATION USE_PREV_WF (shift k > 0 starts from the converged
               wavefunction of shift k - 1, so every shift keeps the same electronic state;
               shift 0 still starts from the input's SCF_GUESS, as the labels did); the
               REFTRAJ reads pool.xyz (n_shifts snapshots); and the setting (CUTOFF,
               REL_CUTOFF, optionally another Na basis set and pseudopotential);
  pool.xyz     the legacy snapshot shifted rigidly along x by k*h/n_shifts, k = 0..n-1,
               h = cell/N, N = grid_points(cell, CUTOFF): the expected finest-grid size;
  ref_frc.xyz  the legacy label forces of that snapshot (Ha/bohr): shift 0 at the qz
               setting must reproduce them;
  the coordinate include, the basis, potential and D3 files (copied; sha256 in
  run_info.json), and job.sh (one CP2K run on the configured node).
runs/RUN/run_info.json records the commit, the config sha256 and, per run, the shifts.

Checks here: machine detected, CP2K module and partition in its YAML; clean tree (commit
recorded); frames.tsv matches its checksum list and the frame is training-side (train or
valid, never test); atom count, element order and cell match the config; every edit hits
exactly one line and the base input is the qz protocol (700/70, USE_GUESS); every KIND's
basis set and potential exist in the files the input names; the run dir is new.
Standard library only; runs on Python >= 3.6.
"""
import argparse
import datetime
import json
import math
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import machine_config as mc  # noqa: E402
import prep_mace_train as pm  # noqa: E402  (git, sha256, parse_time)

BOHR_A = 0.529177210903          # CODATA 2018
HA_BOHR_TO_EV_A = 51.42208619083  # 27.211386245988 / 0.529177210903
QZ = {"CUTOFF": "700", "REL_CUTOFF": "70", "EXTRAPOLATION": "USE_GUESS"}
TOP_KEYS = {"description", "legacy_root", "frames_tsv", "frames_tsv_sums", "cp2k_data_dir",
            "n_shifts", "frames", "settings", "runs", "slurm"}
FRAME_KEYS = {"dir", "snapshot", "forces_file", "natoms", "cell"}
SETTING_KEYS = {"cutoff", "rel_cutoff", "na"}
NA_KEYS = {"basis_set", "basis_file", "potential", "potential_file"}
SLURM_KEYS = {"partition", "nodelist", "ntasks", "cpus_per_task", "layout_source"}

JOB = """#!/bin/bash
# Generated by scripts/prep_na_translation.py at commit {commit}; re-run it instead of editing.
# Layout: {ntasks} MPI x {cpt} OpenMP; source: {layout_source}
#SBATCH --job-name={jobname}
#SBATCH -N 1
#SBATCH -n {ntasks}
#SBATCH --cpus-per-task={cpt}
#SBATCH -p {partition}
#SBATCH -w {nodelist}
#SBATCH --output=slurm-%j.out
#SBATCH --error=slurm-%j.err
#SBATCH --time={time}
#SBATCH --mem=0
set -euo pipefail
[ -e relabel.out ] && {{ echo "relabel.out exists: refusing to overwrite" >&2; exit 1; }}
module purge
module load {module}
export OMP_NUM_THREADS=$SLURM_CPUS_PER_TASK
export MKL_NUM_THREADS=$SLURM_CPUS_PER_TASK
export STACKSIZE=1G
export LIBXSMM_DEFAULT_QUANTIZATION=1
echo "start $(date '+%F %T') on $(hostname)"
mpirun --mca opal_set_max_sys_limits 1 --mca btl ^openib \\
       cp2k.psmp -i relabel.inp -o relabel.out
echo "end $(date '+%F %T')"
"""


class PrepError(Exception):
    pass


# ----------------------------------------------------------------------------- grid
def _smooth(n):
    for p in (2, 3, 5):
        while n % p == 0:
            n //= p
    return n == 1


def grid_points(length_a, cutoff_ry):
    """Expected CP2K grid size along a cell edge: the smallest 2^a 3^b 5^c >= L*sqrt(E)/pi
    (L in bohr, E in Ry). Reproduces the grid sizes of the 2026-11-19 fit (journal). The
    test prints the real grids (PRINT_LEVEL MEDIUM); the analysis uses those."""
    n = int(math.ceil(length_a / BOHR_A * math.sqrt(cutoff_ry) / math.pi))
    while not _smooth(n):
        n += 1
    return n


# ----------------------------------------------------------------------------- xyz
def read_xyz_frame(text, index, src):
    """Snapshot `index` (1-based) of a multi-frame xyz -> (natoms, comment, [(el, x, y, z)])."""
    lines = text.splitlines()
    pos, k = 0, 0
    while pos < len(lines):
        if not lines[pos].strip():
            pos += 1
            continue
        try:
            n = int(lines[pos].split()[0])
        except ValueError:
            raise PrepError("{}: line {}: expected an atom count".format(src, pos + 1))
        k += 1
        block = lines[pos + 2:pos + 2 + n]
        if len(block) != n:
            raise PrepError("{}: snapshot {} truncated".format(src, k))
        if k == index:
            atoms = []
            for line in block:
                t = line.split()
                atoms.append((t[0], float(t[1]), float(t[2]), float(t[3])))
            return n, lines[pos + 1], atoms
        pos += 2 + n
    raise PrepError("{}: has {} snapshots, no snapshot {}".format(src, k, index))


def read_forces(text, index, src):
    """Snapshot `index` of a CP2K force file -> [(el, fx, fy, fz)] in Ha/bohr. Accepts the
    &MOTION &PRINT &FORCES xyz format and the &FORCE_EVAL &PRINT &FORCES table."""
    if "ATOMIC FORCES in [a.u.]" not in text:
        _, _, atoms = read_xyz_frame(text, index, src)
        return atoms
    blocks = text.split("ATOMIC FORCES in [a.u.]")[1:]
    if index > len(blocks):
        raise PrepError("{}: has {} force blocks, no block {}".format(src, len(blocks), index))
    out = []
    for line in blocks[index - 1].splitlines():
        t = line.split()
        if line.strip().startswith("SUM OF ATOMIC FORCES"):
            break
        if len(t) == 6 and t[0].isdigit():
            out.append((t[2], float(t[3]), float(t[4]), float(t[5])))
    return out


def write_xyz(frames):
    """frames: [(comment, [(el, a, b, c)])] -> multi-frame xyz text."""
    out = []
    for comment, atoms in frames:
        out.append(str(len(atoms)))
        out.append(comment)
        for el, a, b, c in atoms:
            out.append("{:<3s} {:18.10f} {:18.10f} {:18.10f}".format(el, a, b, c))
    return "\n".join(out) + "\n"


def shifted(atoms, dx):
    return [(el, x + dx, y, z) for el, x, y, z in atoms]


# ----------------------------------------------------------------------------- input
def kw_values(text, key):
    pat = re.compile(r"^[ \t]*" + re.escape(key) + r"[ \t]+([^\n]*?)[ \t]*$", re.M | re.I)
    return pat.findall(text)


def set_kw(text, key, value, old=None):
    """Replace the single `KEY value` line; `old` (if given) must be the current value."""
    pat = re.compile(r"^([ \t]*)" + re.escape(key) + r"([ \t]+)([^\n]*?)[ \t]*$", re.M)
    hits = pat.findall(text)
    if len(hits) != 1:
        raise PrepError("{}: expected one line, found {}".format(key, len(hits)))
    if old is not None and hits[0][2].split()[0].upper() != old.upper():
        raise PrepError("{}: expected {!r}, found {!r} (not the qz protocol?)".format(
            key, old, hits[0][2]))
    return pat.sub(lambda m: m.group(1) + key + m.group(2) + str(value), text)


KIND_RE = re.compile(r"^([ \t]*)&KIND[ \t]+(\S+)[ \t]*\n(.*?)^[ \t]*&END[ \t]+KIND\b", re.M | re.S)


def kinds(text):
    """-> {kind name: {"element", "basis", "potential", "potential_file"}}."""
    out = {}
    for m in KIND_RE.finditer(text):
        body = m.group(3)
        d = {"element": m.group(2)}
        for line in body.splitlines():
            t = line.split()
            if len(t) >= 2:
                key = t[0].upper()
                if key == "ELEMENT":
                    d["element"] = t[1]
                elif key == "BASIS_SET":
                    d["basis"] = t[-1]
                elif key == "POTENTIAL":
                    d["potential"] = t[1]
                elif key == "POTENTIAL_FILE_NAME":
                    d["potential_file"] = t[1]
        out[m.group(2)] = d
    return out


def swap_na(text, na):
    """Na basis set and pseudopotential from other files (KIND-level POTENTIAL_FILE_NAME, one
    more BASIS_SET_FILE_NAME in &DFT)."""
    ms = [m for m in KIND_RE.finditer(text) if m.group(2) == "Na"]
    if len(ms) != 1:
        raise PrepError("&KIND Na: expected one block, found {}".format(len(ms)))
    m = ms[0]
    body = m.group(3)
    body = set_kw(body, "BASIS_SET", na["basis_set"])
    body = set_kw(body, "POTENTIAL", na["potential"])
    ind = re.search(r"^([ \t]*)POTENTIAL[ \t]", body, re.M).group(1)
    body += "{}POTENTIAL_FILE_NAME {}\n".format(ind, na["potential_file"])
    text = text[:m.start(3)] + body + text[m.end(3):]
    pat = re.compile(r"^([ \t]*)BASIS_SET_FILE_NAME[ \t]+\S+[ \t]*$", re.M)
    hits = list(pat.finditer(text))
    if len(hits) != 1:
        raise PrepError("BASIS_SET_FILE_NAME: expected one line, found {}".format(len(hits)))
    h = hits[0]
    return text[:h.end()] + "\n{}BASIS_SET_FILE_NAME {}".format(h.group(1), na["basis_file"]) \
        + text[h.end():]


def entry_exists(lib_text, element, name):
    for line in lib_text.splitlines():
        t = line.split()
        if len(t) >= 2 and t[0] == element and name in t[1:]:
            return True
    return False


def check_kinds(text, files):
    """Every KIND's basis set and potential exist in the files the input names.
    files: {file name: text}."""
    bfiles = kw_values(text, "BASIS_SET_FILE_NAME")
    pglob = kw_values(text, "POTENTIAL_FILE_NAME")
    errors = []
    for name, d in sorted(kinds(text).items()):
        el = d["element"]
        if "basis" not in d or "potential" not in d:
            errors.append("KIND {}: no BASIS_SET or POTENTIAL".format(name))
            continue
        if not any(entry_exists(files[f], el, d["basis"]) for f in bfiles):
            errors.append("KIND {}: basis {} not in {}".format(name, d["basis"], bfiles))
        pf = d.get("potential_file") or (pglob[0] if pglob else None)
        if pf is None or not entry_exists(files[pf], el, d["potential"]):
            errors.append("KIND {}: potential {} not in {}".format(name, d["potential"], pf))
    if errors:
        raise PrepError("; ".join(errors))


def include_elements(text, kind_map):
    """Elements, in order, of a CP2K &COORD include (kind label -> element via KIND blocks)."""
    els = []
    for line in text.splitlines():
        t = line.split()
        if len(t) >= 4 and not t[0].startswith(("#", "&", "@", "!")):
            lab = t[0]
            els.append(kind_map.get(lab, {}).get("element", re.sub(r"\d+$", "", lab)))
    return els


# ----------------------------------------------------------------------------- config
def load_config(path):
    cfg = json.loads(Path(path).read_text())
    errs = []

    def keys(d, allowed, where, required=None):
        if not isinstance(d, dict):
            errs.append("{}: not an object".format(where))
            return
        for k in sorted(set(d) - allowed):
            errs.append("{}: unknown key {!r}".format(where, k))
        for k in sorted((required if required is not None else allowed) - set(d)):
            errs.append("{}: missing key {!r}".format(where, k))

    keys(cfg, TOP_KEYS, "config")
    if errs:
        raise PrepError("; ".join(errs))
    for n, f in cfg["frames"].items():
        keys(f, FRAME_KEYS, "frames." + n)
    for n, s in cfg["settings"].items():
        keys(s, SETTING_KEYS, "settings." + n, {"cutoff", "rel_cutoff"})
        if "na" in s:
            keys(s["na"], NA_KEYS, "settings.{}.na".format(n))
    keys(cfg["slurm"], SLURM_KEYS, "slurm")
    if not isinstance(cfg["n_shifts"], int) or cfg["n_shifts"] < 2:
        errs.append("n_shifts must be an integer >= 2")
    seen = set()
    for r in cfg["runs"]:
        if len(r) != 3 or r[0] not in cfg["frames"] or r[1] not in cfg["settings"]:
            errs.append("runs: bad entry {!r}".format(r))
            continue
        if (r[0], r[1]) in seen:
            errs.append("runs: duplicate {!r}".format(r[:2]))
        seen.add((r[0], r[1]))
        try:
            pm.parse_time(r[2])
        except pm.PrepError as e:
            errs.append("runs {}: {}".format(r[:2], e))
    if errs:
        raise PrepError("; ".join(errs))
    return cfg


def frame_split(tsv_text, origem, snapshot):
    rows = [l.split("\t") for l in tsv_text.splitlines()]
    head = rows[0]
    io, ifr, idest = head.index("origem"), head.index("frame"), head.index("destino")
    hits = [r for r in rows[1:] if len(r) > idest and r[io] == origem and r[ifr] == str(snapshot)]
    if len(hits) != 1:
        raise PrepError("frames.tsv: {} frame {}: {} rows (expected 1)".format(
            origem, snapshot, len(hits)))
    return hits[0][idest]


def sum_for(sums_text, name):
    for line in sums_text.splitlines():
        t = line.split()
        if len(t) == 2 and t[1].lstrip("*") == name:
            return t[0]
    raise PrepError("checksum list has no {}".format(name))


def find_file(name, dirs):
    for d in dirs:
        p = Path(d) / name
        if p.exists():
            return p.resolve()
    raise PrepError("{}: not found in {}".format(name, [str(d) for d in dirs]))


# ----------------------------------------------------------------------------- prepare
def build_input(base, setting, n_shifts):
    text = base
    text = set_kw(text, "PRINT_LEVEL", "MEDIUM")
    text = set_kw(text, "CUTOFF", setting["cutoff"], old=QZ["CUTOFF"])
    text = set_kw(text, "REL_CUTOFF", setting["rel_cutoff"], old=QZ["REL_CUTOFF"])
    text = set_kw(text, "EXTRAPOLATION", "USE_PREV_WF", old=QZ["EXTRAPOLATION"])
    text = set_kw(text, "TRAJ_FILE_NAME", "pool.xyz")
    text = set_kw(text, "FIRST_SNAPSHOT", 1)
    text = set_kw(text, "LAST_SNAPSHOT", n_shifts)
    text = set_kw(text, "STEPS", n_shifts)
    if "na" in setting:
        text = swap_na(text, setting["na"])
    return text


def prepare(repo, cfg_path, name, machine=None, mcfg=None, now=None):
    repo = Path(repo).resolve()
    cfg_path = Path(cfg_path)
    cfg_path = (cfg_path if cfg_path.is_absolute() else repo / cfg_path).resolve()
    if not cfg_path.is_file():
        raise PrepError("{}: no such config".format(cfg_path))
    if machine is None:
        machine = mc.detect(repo)
        mcfg = mc.load(machine, repo)
    if pm.git(repo, "status", "--porcelain").strip():
        raise PrepError("work tree not clean: commit first (runs record their commit)")
    commit = pm.git(repo, "rev-parse", "HEAD").strip()
    cfg = load_config(cfg_path)
    sl = cfg["slurm"]
    module = mcfg.get("modules", {}).get("cp2k", mc.UNKNOWN)
    if module == mc.UNKNOWN:
        raise PrepError("modules.cp2k unknown in the {} YAML".format(machine))
    if sl["partition"] not in mcfg["partitions"]:
        raise PrepError("partition {!r} not in the {} YAML".format(sl["partition"], machine))

    legacy = Path(cfg["legacy_root"])
    data_dir = Path(cfg["cp2k_data_dir"])
    tsv = legacy / cfg["frames_tsv"]
    sums = (repo / cfg["frames_tsv_sums"])
    if not sums.is_file():
        raise PrepError("{}: no checksum list".format(sums))
    if pm.sha256(tsv) != sum_for(sums.read_text(), tsv.name):
        raise PrepError("{}: sha256 differs from {}".format(tsv, sums))
    tsv_text = tsv.read_text()

    out = repo / "runs" / name
    if out.exists():
        raise PrepError("{}: exists (runs are never overwritten)".format(out))
    plan = []
    for fname, setting_name, wall in cfg["runs"]:
        fr, st = cfg["frames"][fname], cfg["settings"][setting_name]
        src = legacy / fr["dir"]
        split = frame_split(tsv_text, fr["dir"] + "/relabel.out", fr["snapshot"])
        if split not in ("train", "valid"):
            raise PrepError("{}: frame {} is in {!r}; only training-side frames".format(
                fr["dir"], fr["snapshot"], split))
        base = (src / "relabel.inp").read_text()
        abc = [float(x) for x in kw_values(base, "ABC")[0].split()[:3]]
        if any(abs(a - fr["cell"]) > 1e-6 for a in abc):
            raise PrepError("{}: ABC {} != cell {}".format(fr["dir"], abc, fr["cell"]))
        natoms, comment, atoms = read_xyz_frame((src / "pool_lote.xyz").read_text(),
                                                fr["snapshot"], str(src / "pool_lote.xyz"))
        if natoms != fr["natoms"]:
            raise PrepError("{}: {} atoms, config says {}".format(fr["dir"], natoms, fr["natoms"]))
        forces = read_forces((src / fr["forces_file"]).read_text(), fr["snapshot"],
                             str(src / fr["forces_file"]))
        if [a[0] for a in forces] != [a[0] for a in atoms]:
            raise PrepError("{}: force file and pool disagree on elements".format(fr["dir"]))
        text = build_input(base, st, cfg["n_shifts"])
        inc = re.findall(r"^[ \t]*@INCLUDE[ \t]+(\S+)", text, re.M)
        if len(inc) != 1:
            raise PrepError("{}: expected one @INCLUDE, found {}".format(fr["dir"], inc))
        files = {inc[0]: find_file(inc[0], [src])}
        kmap = kinds(text)
        if include_elements(files[inc[0]].read_text(), kmap) != [a[0] for a in atoms]:
            raise PrepError("{}: {} element order differs from the pool".format(fr["dir"], inc[0]))
        libs = kw_values(text, "BASIS_SET_FILE_NAME") + kw_values(text, "POTENTIAL_FILE_NAME") \
            + kw_values(text, "PARAMETER_FILE_NAME")
        for lib in libs:
            files[lib] = find_file(lib, [src, data_dir])
        check_kinds(text, {k: v.read_text() for k, v in files.items() if k in libs})
        n_grid = grid_points(fr["cell"], st["cutoff"])
        h = fr["cell"] / n_grid
        shifts = [k * h / cfg["n_shifts"] for k in range(cfg["n_shifts"])]
        plan.append(dict(frame=fname, setting=setting_name, wall=wall, src=src, text=text,
                         files=files, atoms=atoms, forces=forces, comment=comment,
                         n_grid=n_grid, h=h, shifts=shifts, split=split, fr=fr, st=st))

    out.mkdir(parents=True)
    info = {"created": (now or datetime.datetime.now()).isoformat(timespec="seconds"),
            "machine": machine, "commit": commit, "config": str(cfg_path.relative_to(repo)),
            "config_sha256": pm.sha256(cfg_path), "frames_tsv_sha256": pm.sha256(tsv),
            "n_shifts": cfg["n_shifts"], "runs": {}}
    cmds = []
    for p in plan:
        rd = out / "{}-{}".format(p["frame"], p["setting"])
        rd.mkdir()
        (rd / "relabel.inp").write_text(p["text"])
        pool = [("shift_k={} dx_A={:.10f} | legacy {} snapshot {} | {}".format(
            k, dx, p["fr"]["dir"], p["fr"]["snapshot"], p["comment"].strip()),
            shifted(p["atoms"], dx)) for k, dx in enumerate(p["shifts"])]
        (rd / "pool.xyz").write_text(write_xyz(pool))
        (rd / "ref_frc.xyz").write_text(write_xyz([(
            "legacy label forces [Ha/bohr] | {} snapshot {}".format(
                p["fr"]["dir"] + "/" + p["fr"]["forces_file"], p["fr"]["snapshot"]),
            p["forces"])]))
        sha = {}
        for fn, srcp in sorted(p["files"].items()):
            shutil.copyfile(str(srcp), str(rd / fn))
            sha[fn] = {"source": str(srcp), "sha256": pm.sha256(rd / fn)}
        (rd / "job.sh").write_text(JOB.format(
            commit=commit, ntasks=sl["ntasks"], cpt=sl["cpus_per_task"],
            layout_source=sl["layout_source"], partition=sl["partition"],
            nodelist=sl["nodelist"], time=p["wall"], module=module,
            jobname="natr-{}-{}".format(p["frame"], p["setting"])))
        info["runs"][rd.name] = {
            "frame": p["frame"], "setting": p["setting"], "split": p["split"],
            "legacy_dir": str(p["src"]), "snapshot": p["fr"]["snapshot"],
            "legacy_inp_sha256": pm.sha256(p["src"] / "relabel.inp"),
            "forces_file": p["fr"]["forces_file"], "cutoff": p["st"]["cutoff"],
            "rel_cutoff": p["st"]["rel_cutoff"], "na": p["st"].get("na"),
            "cell_A": p["fr"]["cell"], "grid_n_expected": p["n_grid"],
            "h_A_expected": p["h"], "shifts_A": p["shifts"], "wall_time": p["wall"],
            "files": sha}
        cmds.append("cd {} && sbatch job.sh".format(rd))
    (out / "run_info.json").write_text(json.dumps(info, indent=1, sort_keys=True) + "\n")
    return out, cmds


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("config")
    ap.add_argument("--name", required=True, help="run dir name under runs/")
    a = ap.parse_args(argv)
    repo = Path(__file__).resolve().parent.parent
    try:
        out, cmds = prepare(repo, a.config, a.name)
    except (PrepError, pm.PrepError, mc.ConfigError, OSError, ValueError) as e:
        print("prep_na_translation: " + str(e), file=sys.stderr)
        return 1
    print("prepared {} (nothing submitted). To submit (ask first):".format(out))
    for c in cmds:
        print("  " + c)
    return 0


if __name__ == "__main__":
    sys.exit(main())

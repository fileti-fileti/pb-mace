#!/usr/bin/env python3
"""Prepare the translation test v2 of the qz force labels (docs/na-label-grid-error.md).

v1 (prep_na_translation.py) let the SCF of each shift find its own state; three runs
changed state between shifts. v2 holds the electronic state: every shift is its own CP2K
single point that starts from the same converged wavefunction (seed.wfn) in the state of
the legacy label, with the full U from the first SCF step (as the owner's
conv_test/pb_conv.py did).

Usage (headnode, clean work tree; nothing is submitted, the sbatch commands are printed):
  prep_na_translation_v2.py CONFIG --name RUN

CONFIG: configs/na_translation/*_v2.json. Per entry of "runs" ([frame, setting, wall time])
this writes runs/RUN/<frame>-<setting>/ with
  relabel.inp   the frame's legacy qz input with only these edits: PRINT_LEVEL MEDIUM;
                the setting (CUTOFF, REL_CUTOFF, optional Na basis/potential); SCF_GUESS
                RESTART from WFN_RESTART_FILE_NAME seed.wfn; U_RAMPING 0.0 and no
                INIT_U_RAMPING_EACH_SCF (full U from the seed); REFTRAJ on one snapshot
                (pool.xyz). EXTRAPOLATION stays USE_GUESS (one step per run);
  shift_K/      K = 0..n_shifts-1: pool.xyz (the snapshot shifted rigidly along x by
                K*h/n_shifts, h = cell/N), a copy of relabel.inp, symlinks to the shared files;
  seed.wfn      copied from the setting's seed (a converged wavefunction in the label's
                state; sha256 in run_info.json), or, for seed "generate", written by the job
                from seed_gen/ (the unshifted snapshot with the label protocol: SCF_GUESS
                ATOMIC and the U ramping of the labels);
  ref_frc.xyz   the legacy label forces of the snapshot (Ha/bohr);
  coordinate include, basis/potential/D3 files and job.sh (runs the shifts in turn; a
  shift whose relabel.out ended is skipped, so a resubmission resumes).
N: frames.<f>.grid_n[cutoff] when given (read from earlier CP2K outputs), else
prep_na_translation.grid_points(); the analysis reads the real N from the outputs.
run_info.json also records the Fe Mulliken spins of the legacy label (the state to hold).

Checks here: as prep_na_translation.py (machine, clean tree, frames.tsv checksum,
training-side frame, atoms, element order, cell, single-line edits on the qz protocol,
basis and potential entries), plus: each seed file exists, the edits that hold the state
find the label protocol (SCF_GUESS ATOMIC, U ramping 0.5 eV each SCF), the legacy label has
Fe spins.
Standard library only; runs on Python >= 3.6.
"""
import argparse
import datetime
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
import machine_config as mc  # noqa: E402
import prep_mace_train as pm  # noqa: E402
import prep_na_translation as pt  # noqa: E402
from prep_na_translation import PrepError  # noqa: E402

TOP_KEYS = pt.TOP_KEYS
FRAME_KEYS = pt.FRAME_KEYS | {"grid_n", "seeds"}
SETTING_KEYS = pt.SETTING_KEYS | {"seed"}
GENERATE = "generate"

JOB = """#!/bin/bash
# Generated by scripts/prep_na_translation_v2.py at commit {commit}; re-run it instead of editing.
# Layout: {ntasks} MPI x {cpt} OpenMP; source: {layout_source}
#SBATCH --job-name={jobname}
#SBATCH -N 1
#SBATCH -n {ntasks}
#SBATCH --cpus-per-task={cpt}
#SBATCH -p {partition}
#SBATCH -w {nodelist}
#SBATCH --output=slurm-%j.out
#SBATCH --error=slurm-%j.err
#SBATCH --time={time}
#SBATCH --mem=0
set -euo pipefail
module purge
module load {module}
export OMP_NUM_THREADS=$SLURM_CPUS_PER_TASK
export MKL_NUM_THREADS=$SLURM_CPUS_PER_TASK
export STACKSIZE=1G
export LIBXSMM_DEFAULT_QUANTIZATION=1
RUNDIR=$PWD
cp2k_in() {{  # run CP2K in dir $1 unless its relabel.out already ended
  cd "$RUNDIR/$1"
  if grep -q "PROGRAM ENDED" relabel.out 2>/dev/null; then echo "$1: done, skipped"; return; fi
  [ -e relabel.out ] && mv relabel.out "relabel.out.partial.$SLURM_JOB_ID"
  echo "$1: start $(date '+%F %T')"
  mpirun --mca opal_set_max_sys_limits 1 --mca btl ^openib \\
         cp2k.psmp -i relabel.inp -o relabel.out
  echo "$1: end $(date '+%F %T')"
}}
echo "start $(date '+%F %T') on $(hostname)"
{seed_block}
[ -s "$RUNDIR/seed.wfn" ] || {{ echo "no seed.wfn: stop" >&2; exit 1; }}
for k in $(seq 0 {last}); do cp2k_in shift_$k; done
echo "end $(date '+%F %T')"
"""
SEED_GEN = """cp2k_in seed_gen
cd "$RUNDIR"
[ -s seed.wfn ] || cp seed_gen/{project}-RESTART.wfn seed.wfn"""


def del_kw(text, key, old):
    """Remove the single `KEY old` line."""
    pat = re.compile(r"^[ \t]*" + re.escape(key) + r"[ \t]+([^\n]*?)[ \t]*\n", re.M)
    hits = pat.findall(text)
    if hits != [old]:
        raise PrepError("{}: expected one line {!r}, found {}".format(key, old, hits))
    return pat.sub("", text)


def set_exact(text, key, value, old):
    if pt.kw_values(text, key) != [old]:
        raise PrepError("{}: expected one line {!r}, found {}".format(
            key, old, pt.kw_values(text, key)))
    return pt.set_kw(text, key, value)


def add_after_first(text, key, line):
    """Insert `line` (same indentation) after the first `KEY ...` line."""
    m = re.search(r"^([ \t]*)" + re.escape(key) + r"[ \t]+[^\n]*\n", text, re.M)
    if not m:
        raise PrepError("{}: not found".format(key))
    return text[:m.end()] + m.group(1) + line + "\n" + text[m.end():]


def one_snapshot(text):
    text = pt.set_kw(text, "PRINT_LEVEL", "MEDIUM")
    text = pt.set_kw(text, "TRAJ_FILE_NAME", "pool.xyz")
    text = pt.set_kw(text, "FIRST_SNAPSHOT", 1)
    text = pt.set_kw(text, "LAST_SNAPSHOT", 1)
    return pt.set_kw(text, "STEPS", 1)


def build_inputs(base, setting):
    """-> (seeded input for the shifts, label-protocol input for seed_gen)."""
    text = pt.set_kw(base, "CUTOFF", setting["cutoff"], old=pt.QZ["CUTOFF"])
    text = pt.set_kw(text, "REL_CUTOFF", setting["rel_cutoff"], old=pt.QZ["REL_CUTOFF"])
    if pt.kw_values(text, "EXTRAPOLATION") != [pt.QZ["EXTRAPOLATION"]]:
        raise PrepError("EXTRAPOLATION: not the qz protocol")
    if "na" in setting:
        text = pt.swap_na(text, setting["na"])
    text = one_snapshot(text)
    gen = text
    text = set_exact(text, "SCF_GUESS", "RESTART", "ATOMIC")
    text = add_after_first(text, "POTENTIAL_FILE_NAME", "WFN_RESTART_FILE_NAME seed.wfn")
    text = del_kw(text, "INIT_U_RAMPING_EACH_SCF", "T")
    text = set_exact(text, "U_RAMPING", "[eV] 0.0", "[eV] 0.5")
    return text, gen


def legacy_fe_spins(out_text, snapshot):
    import na_translation as nt   # src/; parse_out only
    steps = nt.parse_out(out_text)["steps"]
    if len(steps) < snapshot or not steps[snapshot - 1]["fe_spins"]:
        raise PrepError("legacy relabel.out: no Fe spins for snapshot {}".format(snapshot))
    return {str(k): v for k, v in sorted(steps[snapshot - 1]["fe_spins"].items())}


def load_config(path):
    cfg = json.loads(Path(path).read_text())
    errs = []
    for k in sorted(set(cfg) ^ TOP_KEYS):
        errs.append("config: {} key {!r}".format("unknown" if k in cfg else "missing", k))
    if errs:
        raise PrepError("; ".join(errs))
    for n, f in cfg["frames"].items():
        for k in sorted(set(f) - FRAME_KEYS):
            errs.append("frames.{}: unknown key {!r}".format(n, k))
        for k in sorted(pt.FRAME_KEYS - set(f)):
            errs.append("frames.{}: missing key {!r}".format(n, k))
    for n, s in cfg["settings"].items():
        for k in sorted(set(s) - SETTING_KEYS):
            errs.append("settings.{}: unknown key {!r}".format(n, k))
        for k in ("cutoff", "rel_cutoff", "seed"):
            if k not in s:
                errs.append("settings.{}: missing key {!r}".format(n, k))
    if not isinstance(cfg["n_shifts"], int) or cfg["n_shifts"] < 2:
        errs.append("n_shifts must be an integer >= 2")
    seen = set()
    for r in cfg["runs"]:
        if len(r) != 3 or r[0] not in cfg["frames"] or r[1] not in cfg["settings"]:
            errs.append("runs: bad entry {!r}".format(r))
            continue
        if tuple(r[:2]) in seen:
            errs.append("runs: duplicate {!r}".format(r[:2]))
        seen.add(tuple(r[:2]))
        seed = cfg["settings"][r[1]]["seed"]
        if seed != GENERATE and seed not in cfg["frames"][r[0]].get("seeds", {}):
            errs.append("runs {}: frame has no seed {!r}".format(r[:2], seed))
        try:
            pm.parse_time(r[2])
        except pm.PrepError as e:
            errs.append("runs {}: {}".format(r[:2], e))
    if errs:
        raise PrepError("; ".join(errs))
    return cfg


def prepare(repo, cfg_path, name, machine=None, mcfg=None, now=None):
    repo = Path(repo).resolve()
    cfg_path = Path(cfg_path)
    cfg_path = (cfg_path if cfg_path.is_absolute() else repo / cfg_path).resolve()
    if not cfg_path.is_file():
        raise PrepError("{}: no such config".format(cfg_path))
    if machine is None:
        machine = mc.detect(repo)
        mcfg = mc.load(machine, repo)
    if pm.git(repo, "status", "--porcelain").strip():
        raise PrepError("work tree not clean: commit first (runs record their commit)")
    commit = pm.git(repo, "rev-parse", "HEAD").strip()
    cfg = load_config(cfg_path)
    sl = cfg["slurm"]
    module = mcfg.get("modules", {}).get("cp2k", mc.UNKNOWN)
    if module == mc.UNKNOWN:
        raise PrepError("modules.cp2k unknown in the {} YAML".format(machine))
    if sl["partition"] not in mcfg["partitions"]:
        raise PrepError("partition {!r} not in the {} YAML".format(sl["partition"], machine))
    legacy, data_dir = Path(cfg["legacy_root"]), Path(cfg["cp2k_data_dir"])
    tsv, sums = legacy / cfg["frames_tsv"], repo / cfg["frames_tsv_sums"]
    if not sums.is_file() or pm.sha256(tsv) != pt.sum_for(sums.read_text(), tsv.name):
        raise PrepError("{}: missing checksum list or sha256 differs".format(tsv))
    tsv_text = tsv.read_text()
    out = repo / "runs" / name
    if out.exists():
        raise PrepError("{}: exists (runs are never overwritten)".format(out))

    plan = []
    for fname, sname, wall in cfg["runs"]:
        fr, st = cfg["frames"][fname], cfg["settings"][sname]
        src = legacy / fr["dir"]
        split = pt.frame_split(tsv_text, fr["dir"] + "/relabel.out", fr["snapshot"])
        if split not in ("train", "valid"):
            raise PrepError("{}: frame {} is in {!r}; only training-side frames".format(
                fr["dir"], fr["snapshot"], split))
        base = (src / "relabel.inp").read_text()
        abc = [float(x) for x in pt.kw_values(base, "ABC")[0].split()[:3]]
        if any(abs(a - fr["cell"]) > 1e-6 for a in abc):
            raise PrepError("{}: ABC {} != cell {}".format(fr["dir"], abc, fr["cell"]))
        natoms, comment, atoms = pt.read_xyz_frame((src / "pool_lote.xyz").read_text(),
                                                   fr["snapshot"], str(src / "pool_lote.xyz"))
        if natoms != fr["natoms"]:
            raise PrepError("{}: {} atoms, config says {}".format(fr["dir"], natoms, fr["natoms"]))
        forces = pt.read_forces((src / fr["forces_file"]).read_text(), fr["snapshot"],
                                str(src / fr["forces_file"]))
        if [a[0] for a in forces] != [a[0] for a in atoms]:
            raise PrepError("{}: force file and pool disagree on elements".format(fr["dir"]))
        spins = legacy_fe_spins((src / "relabel.out").read_text(), fr["snapshot"])
        text, gen = build_inputs(base, st)
        inc = re.findall(r"^[ \t]*@INCLUDE[ \t]+(\S+)", text, re.M)
        if len(inc) != 1:
            raise PrepError("{}: expected one @INCLUDE, found {}".format(fr["dir"], inc))
        files = {inc[0]: pt.find_file(inc[0], [src])}
        if pt.include_elements(files[inc[0]].read_text(), pt.kinds(text)) != [a[0] for a in atoms]:
            raise PrepError("{}: {} element order differs from the pool".format(fr["dir"], inc[0]))
        libs = pt.kw_values(text, "BASIS_SET_FILE_NAME") + \
            [v for v in pt.kw_values(text, "POTENTIAL_FILE_NAME")] + \
            pt.kw_values(text, "PARAMETER_FILE_NAME")
        for lib in libs:
            files[lib] = pt.find_file(lib, [src, data_dir])
        pt.check_kinds(text, {k: v.read_text() for k, v in files.items() if k in libs})
        seed = None
        if st["seed"] != GENERATE:
            seed = (repo / fr["seeds"][st["seed"]]).resolve()
            if not seed.is_file() or seed.stat().st_size == 0:
                raise PrepError("seed {}: missing or empty".format(seed))
        n_grid = fr.get("grid_n", {}).get(str(st["cutoff"])) or \
            pt.grid_points(fr["cell"], st["cutoff"])
        h = fr["cell"] / n_grid
        shifts = [k * h / cfg["n_shifts"] for k in range(cfg["n_shifts"])]
        project = pt.kw_values(base, "PROJECT")[0]
        plan.append(dict(frame=fname, setting=sname, wall=wall, src=src, text=text, gen=gen,
                         files=files, atoms=atoms, forces=forces, comment=comment, seed=seed,
                         n_grid=n_grid, h=h, shifts=shifts, split=split, fr=fr, st=st,
                         spins=spins, project=project))

    out.mkdir(parents=True)
    info = {"created": (now or datetime.datetime.now()).isoformat(timespec="seconds"),
            "machine": machine, "commit": commit, "config": str(cfg_path.relative_to(repo)),
            "config_sha256": pm.sha256(cfg_path), "frames_tsv_sha256": pm.sha256(tsv),
            "layout": "per_shift", "reading": "v2", "n_shifts": cfg["n_shifts"], "runs": {}}
    cmds = []
    for p in plan:
        rd = out / "{}-{}".format(p["frame"], p["setting"])
        rd.mkdir()
        (rd / "relabel.inp").write_text(p["text"])
        (rd / "ref_frc.xyz").write_text(pt.write_xyz([(
            "legacy label forces [Ha/bohr] | {} snapshot {}".format(
                p["fr"]["dir"] + "/" + p["fr"]["forces_file"], p["fr"]["snapshot"]),
            p["forces"])]))
        sha = {}
        for fn, srcp in sorted(p["files"].items()):
            shutil.copyfile(str(srcp), str(rd / fn))
            sha[fn] = {"source": str(srcp), "sha256": pm.sha256(rd / fn)}
        shared = sorted(p["files"]) + ["seed.wfn"]
        if p["seed"] is not None:
            shutil.copyfile(str(p["seed"]), str(rd / "seed.wfn"))
            sha["seed.wfn"] = {"source": str(p["seed"]), "sha256": pm.sha256(rd / "seed.wfn")}
        dirs = [("shift_{}".format(k), p["text"], dx) for k, dx in enumerate(p["shifts"])]
        if p["seed"] is None:
            dirs.insert(0, ("seed_gen", p["gen"], 0.0))
        for dname, inp, dx in dirs:
            d = rd / dname
            d.mkdir()
            (d / "relabel.inp").write_text(inp)
            (d / "pool.xyz").write_text(pt.write_xyz([(
                "{} dx_A={:.10f} | legacy {} snapshot {} | {}".format(
                    dname, dx, p["fr"]["dir"], p["fr"]["snapshot"], p["comment"].strip()),
                pt.shifted(p["atoms"], dx))]))
            for fn in shared:
                if dname == "seed_gen" and fn == "seed.wfn":
                    continue
                (d / fn).symlink_to(Path("..") / fn)
        seed_block = SEED_GEN.format(project=p["project"]) if p["seed"] is None else ""
        (rd / "job.sh").write_text(JOB.format(
            commit=commit, ntasks=sl["ntasks"], cpt=sl["cpus_per_task"],
            layout_source=sl["layout_source"], partition=sl["partition"],
            nodelist=sl["nodelist"], time=p["wall"], module=module, seed_block=seed_block,
            last=cfg["n_shifts"] - 1, jobname="natr2-{}-{}".format(p["frame"], p["setting"])))
        info["runs"][rd.name] = {
            "frame": p["frame"], "setting": p["setting"], "split": p["split"],
            "legacy_dir": str(p["src"]), "snapshot": p["fr"]["snapshot"],
            "legacy_inp_sha256": pm.sha256(p["src"] / "relabel.inp"),
            "forces_file": p["fr"]["forces_file"], "project": p["project"],
            "cutoff": p["st"]["cutoff"], "rel_cutoff": p["st"]["rel_cutoff"],
            "na": p["st"].get("na"), "seed": p["st"]["seed"], "cell_A": p["fr"]["cell"],
            "grid_n_used": p["n_grid"], "h_A_used": p["h"], "shifts_A": p["shifts"],
            "legacy_fe_spins": p["spins"], "wall_time": p["wall"], "files": sha}
        cmds.append("cd {} && sbatch job.sh".format(rd))
    (out / "run_info.json").write_text(json.dumps(info, indent=1, sort_keys=True) + "\n")
    return out, cmds


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("config")
    ap.add_argument("--name", required=True, help="run dir name under runs/")
    a = ap.parse_args(argv)
    repo = Path(__file__).resolve().parent.parent
    try:
        out, cmds = prepare(repo, a.config, a.name)
    except (PrepError, pm.PrepError, mc.ConfigError, OSError, ValueError) as e:
        print("prep_na_translation_v2: " + str(e), file=sys.stderr)
        return 1
    print("prepared {} (nothing submitted). To submit (ask first):".format(out))
    for c in cmds:
        print("  " + c)
    return 0


if __name__ == "__main__":
    sys.exit(main())

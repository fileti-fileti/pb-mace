#!/usr/bin/env python3
"""Prepare MLMD runs (LAMMPS + MACE) for the RDF comparison: docs/rdf-mlmd-vs-aimd.md.

Usage (login node, clean work tree; nothing is submitted, the command is printed):
  prep_mlmd.py CONFIG --system NAME --name RUN --partition P --time T [--exclude NODES]
               [--cpus 6] [--env mace_env]
  prep_mlmd.py CONFIG --check --name RUN --partition P [--time 00:20:00] [...]

CONFIG: configs/mlmd/*.json (model, temperature, thermostat, replicas, seeds, masses; per
system: start extxyz and config_type, expected Fe2/Fe3 counts, cell, dt_fs, nsteps,
dump_every). The start structure is the first frame of the config_type in the start file (a
frame of the system's AIMD run, training side), wrapped into the orthorhombic cell; atom
order is kept. Fe2/Fe3 from its geometry: Fe2 = Fe with a C within 2.4 A, Fe3 = the other
Fe; the counts must equal fe2_fe3 (the AIMD reference). Written to kinds.inc (CP2K &COORD
style, read by src/rdf.py) in the run dir.

Production (--system): runs/RUN/ with start.data, in.lmp, rep1..repN/ and one job that runs
the replicas in turn (seed = seed_base + k): NVT (Nose-Hoover chain), new Maxwell-Boltzmann
velocities, frames every dump_every steps to repK/traj.xyz (LAMMPS xyz: rdf.py reads it with
the system's dt_fs). Per replica: DONE; UNSTABLE (lost atoms, non-numeric coordinates or a
nan/inf in the log: a model failure, counted by the reading rule); FAIL (any other error:
resubmit, finished replicas are skipped). Run DONE when every replica is DONE.
Check (--check, a test job): runs/RUN/<system>/ for every system: LAMMPS run 0 (energy,
forces) and a short NVT run (bench_steps; timesteps/s), mace_eval_configs on the same frame
with the source model, then src/compare_lammps_eval.py -> RUN/check.tsv (pass: energy within
1e-6 eV/atom, every force component within 1e-5 eV/A).
Checks here: machine detected, clean tree (commit recorded), partition, env and LAMMPS in
the machine YAML, the LAMMPS libraries resolve (ldd) with lammps_ld_library_path, the start
file is in its checksum list (data/<set>.sha256) and every listed file matches, the frame's
cell is the configured cell, the Fe2/Fe3 counts match, model files exist (sha256 recorded),
the run dir is new.
Standard library only; runs on Python >= 3.6.
"""
import argparse
import datetime
import json
import os
import re
import socket
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import machine_config as mc  # noqa: E402
import prep_mace_train as pm  # noqa: E402  (git, sha256, checksums, env, wall time)

ELEMENT_ORDER = ("Fe", "C", "N", "Na", "O", "H")   # LAMMPS atom types, in this order
KV_RE = re.compile(r'([A-Za-z_][\w-]*)=("([^"]*)"|\S+)')
FE2_CUTOFF = 2.4   # A: Fe-C bond ~1.9 A; Fe-N ~2.0 A, Fe-O ~2.2 A (no C that close to Fe3)
SYSTEM_KEYS = {"start", "config_type", "fe2_fe3", "cell", "dt_fs", "nsteps", "dump_every"}
TOP_KEYS = {"description", "model", "model_source", "lammps_ld_library_path",
            "temperature_K", "tdamp_fs", "replicas", "seed_base", "bench_steps", "masses",
            "systems"}

IN_HEAD = """# Generated by scripts/prep_mlmd.py at commit {commit}; re-run it instead of editing.
units           metal
atom_style      atomic
atom_modify     map yes
newton          on
boundary        p p p
read_data       {data}
pair_style      mace no_domain_decomposition
pair_coeff      * * {model} {elements}
neighbor        2.0 bin
neigh_modify    every 1 delay 0 check yes
timestep        {dt_ps}
"""

IN_PROD = """velocity        all create {temp} ${{SEED}} mom yes rot no dist gaussian
fix             nvt all nvt temp {temp} {temp} {tdamp_ps}
thermo_style    custom step time temp pe ke etotal press
thermo          {dump}
thermo_modify   flush yes
dump            trj all xyz {dump} traj.xyz
dump_modify     trj element {elements} sort id format float %.6f
run             {nsteps}
"""

IN_CHECK = """thermo_style    custom step pe
dump            frc all custom 1 forces.dump id element fx fy fz
dump_modify     frc element {elements} sort id format float %.10f
run             0
undump          frc
print           "PE_START $(pe:%.10f)"
velocity        all create {temp} 12345 mom yes rot no dist gaussian
fix             nvt all nvt temp {temp} {temp} {tdamp_ps}
thermo          50
run             {bench}
"""


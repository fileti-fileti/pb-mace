#!/usr/bin/env python3
"""Prepare a MACE evaluation run: runs/<name>/ with job.sbatch and run_info.json.

Usage (login node, clean work tree; nothing is submitted, the command is printed):
  prep_mace_eval.py MODEL CONFIGS --name NAME --partition P [--exclude NODES]
                    [--time 00:20:00] [--cpus 12] [--batch-size 2] [--env mace_env]

The job runs `mace_eval_configs` (1 GPU, float64) on CONFIGS with MODEL and writes
eval.xyz in the run dir (predictions under MACE_energy / MACE_forces), then DONE or FAIL.
Errors are computed afterwards by src/mace_errors.py (docs/mace-training.md). Checks: the
machine is detected and the work tree is clean (commit recorded); the partition and env are
in the machine YAML; MODEL exists (sha256 recorded); CONFIGS is listed in its checksum list
and every listed file matches; the run dir is new.
Standard library only; runs on Python >= 3.6.
"""
import argparse
import datetime
import json
import socket
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import machine_config as mc  # noqa: E402
import prep_mace_train as pm  # noqa: E402  (shared checks: git, checksums, env, wall time)

SBATCH = """#!/bin/bash
#SBATCH -J {name}
#SBATCH -p {partition}
#SBATCH -N 1
#SBATCH --ntasks=1
#SBATCH --gres=gpu:1
#SBATCH -c {cpus}
#SBATCH -t {time}
{exclude}#SBATCH -o slurm-%j.out
# Generated by scripts/prep_mace_eval.py at commit {commit}; re-run it instead of editing.
cd {run} || exit 1
echo "job=$SLURM_JOB_ID host=$(hostname) start=$(date -Iseconds)"
source {conda_sh} || exit 1
conda activate {env} || exit 1
echo "mace_eval_configs=$(command -v mace_eval_configs)"
nvidia-smi --query-gpu=name,memory.total --format=csv,noheader
mace_eval_configs --configs "{configs}" --model "{model}" --output eval.xyz \\
  --device cuda --default_dtype float64 --batch_size {batch}
rc=$?
echo "mace_eval_configs rc=$rc end=$(date -Iseconds)"
if [ $rc -eq 0 ] && [ -s eval.xyz ]; then
  touch DONE; exit 0
fi
touch FAIL; exit 1
"""


def prepare(repo, machine, mcfg, a, now=None):
    repo = Path(repo).resolve()
    if pm.git(repo, "status", "--porcelain").strip():
        raise pm.PrepError("work tree not clean: commit first (runs record their commit)")
    commit = pm.git(repo, "rev-parse", "HEAD").strip()
    if a.partition not in mcfg["partitions"]:
        raise pm.PrepError("partition {!r} not in the {} YAML".format(a.partition, machine))
    conda_sh = mcfg["python"]["conda_sh"]
    if conda_sh == mc.UNKNOWN or not Path(conda_sh).is_file():
        raise pm.PrepError("python.conda_sh {!r}: unknown or missing".format(conda_sh))
    env = pm.find_env(mcfg, a.env)
    if a.cpus < 1 or a.batch_size < 1:
        raise pm.PrepError("--cpus and --batch-size must be >= 1")
    pm.parse_time(a.time)

    def resolve(p):
        p = Path(p)
        return (p if p.is_absolute() else repo / p).resolve()

    model, configs = resolve(a.model), resolve(a.configs)
    if not model.is_file():
        raise pm.PrepError("{}: no such model".format(model))
    if not configs.is_file():
        raise pm.PrepError("{}: no such configs file".format(configs))
    sf = pm.sums_file(configs)
    sums = pm.verify_sums(sf, configs.parent)
    if str(configs) not in sums:
        raise pm.PrepError("{} not listed in {}".format(configs, sf))

    if not pm.NAME_RE.match(a.name or ""):
        raise pm.PrepError("run name {!r}: use letters, digits, '.', '_' or '-'".format(a.name))
    runs = repo / "runs"
    if not runs.is_dir():
        raise pm.PrepError("{}: no runs/ dir or link".format(runs))
    run = runs / a.name
    if run.exists():
        raise pm.PrepError("{}: run dir exists; pick another --name".format(run))

    sbatch = SBATCH.format(
        name=a.name, partition=a.partition, cpus=a.cpus, time=a.time,
        exclude="#SBATCH --exclude={}\n".format(a.exclude) if a.exclude else "",
        commit=commit, run=run, conda_sh=conda_sh, env=env, configs=configs, model=model,
        batch=a.batch_size)
    info = {
        "created": (now or datetime.datetime.now()).isoformat(timespec="seconds"),
        "machine": machine, "host": socket.gethostname(), "commit": commit,
        "model": {"path": str(model), "sha256": pm.sha256(model)},
        "configs": {"path": str(configs), "sha256": sums[str(configs)], "list": str(sf)},
        "slurm": {"partition": a.partition, "exclude": a.exclude, "cpus": a.cpus,
                  "time": a.time},
        "batch_size": a.batch_size, "conda_sh": conda_sh, "env": env, "output": "eval.xyz",
    }
    run.mkdir()
    (run / "job.sbatch").write_text(sbatch)
    (run / "run_info.json").write_text(json.dumps(info, indent=2) + "\n")
    return run


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--repo", default=str(mc.DEFAULT_REPO), help=argparse.SUPPRESS)
    ap.add_argument("model")
    ap.add_argument("configs")
    ap.add_argument("--name", required=True)
    ap.add_argument("--partition", required=True)
    ap.add_argument("--exclude", default="")
    ap.add_argument("--time", default="00:20:00")
    ap.add_argument("--cpus", type=int, default=12)
    ap.add_argument("--batch-size", type=int, default=2)
    ap.add_argument("--env", default="mace_env")
    a = ap.parse_args(argv)
    try:
        machine = mc.detect(a.repo)
        run = prepare(a.repo, machine, mc.load(machine, a.repo), a)
    except (pm.PrepError, mc.ConfigError) as e:
        print("ERROR: {}".format(e), file=sys.stderr)
        return 1
    print("prepared {}".format(run))
    print("submit (ask first): cd {} && sbatch job.sbatch".format(run))
    return 0


if __name__ == "__main__":
    sys.exit(main())
